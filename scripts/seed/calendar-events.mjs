// Builds 0063_demo_calendar_events.sql: the institutional calendar of the demo organization (1.3.4).
// Applies the Guatemala reference template, generates 2026, and adds the dates the agenda should be able to show:
// fourth-bimester exams, 2027 admissions and enrollment, one extracurricular activity and the closing ceremony.
// Only runs in org-demo and only inserts what is not already there. Run: node scripts/seed/calendar-events.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { guatemalaTemplate, occurrences } from "../../packages/domain/src/calendar-rules.ts";

const ORG = "org-demo", ADMIN = "user-0", AT = "2026-10-29T15:00:00.000Z";
const q = value => value === null || value === undefined ? "NULL" : typeof value === "number" ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const uuid = name => { const h = createHash("sha256").update(`hl-calendar:${name}`).digest("hex"); return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`; };
const calendar = `(SELECT id FROM calendars WHERE organization_id='${ORG}' AND scope='organization')`;
const category = key => `(SELECT id FROM calendar_categories WHERE organization_id='${ORG}' AND key='${key}')`;
const guard = `EXISTS(SELECT 1 FROM organizations WHERE id='${ORG}')`;

const lines = [
  "-- Generated by scripts/seed/calendar-events.mjs. Do not edit by hand.",
  "-- Guatemala reference template applied to the demo organization, 2026 generated, plus the fourth-bimester exams,",
  "-- 2027 admissions and enrollment, one extracurricular activity and the closing ceremony. Only org-demo, and only",
  "-- what is not already there.",
  `INSERT INTO calendars(id,organization_id,scope,scope_id,name,created_at,updated_at) SELECT ${q(`calendar-${uuid("org")}`)},${q(ORG)},'organization',NULL,'Calendario institucional',${q(AT)},${q(AT)} WHERE ${guard} AND NOT EXISTS(SELECT 1 FROM calendars WHERE organization_id='${ORG}' AND scope='organization');`,
];
const rules = guatemalaTemplate.map(template => ({ ...template, id: `rule-${uuid(template.id)}` }));
for (const rule of rules) {
  lines.push(`INSERT INTO calendar_rules(id,calendar_id,organization_id,category_id,rule,no_class,created_by,created_at,updated_at) SELECT ${q(rule.id)},${calendar},${q(ORG)},${category("holiday")},${q(JSON.stringify(rule))},1,${q(ADMIN)},${q(AT)},${q(AT)} WHERE ${guard} AND ${calendar} IS NOT NULL AND NOT EXISTS(SELECT 1 FROM calendar_rules WHERE calendar_id=${calendar} AND lower(json_extract(rule,'$.title'))=lower(${q(rule.title)}));`);
}
for (const item of occurrences(rules, 2026)) {
  const id = `event-${uuid(`2026-${item.ruleId}`)}`;
  lines.push(`INSERT INTO calendar_events(id,calendar_id,organization_id,category_id,title,starts_on,ends_on,part,no_class,rule_id,year,status,created_by,created_at,updated_at) SELECT ${q(id)},${calendar},${q(ORG)},${category("holiday")},${q(item.title)},${q(item.from)},${q(item.until)},${q(item.part || "full")},1,(SELECT id FROM calendar_rules WHERE id=${q(item.ruleId)} AND calendar_id=${calendar}),2026,'active',${q(ADMIN)},${q(AT)},${q(AT)} WHERE ${guard} AND EXISTS(SELECT 1 FROM calendar_rules WHERE id=${q(item.ruleId)} AND calendar_id=${calendar}) AND NOT EXISTS(SELECT 1 FROM calendar_events WHERE rule_id=${q(item.ruleId)} AND year=2026);`);
}
const once = [
  ["exams", "Exámenes del cuarto bimestre", "2026-11-16", "2026-11-27", 0],
  ["admissions", "Admisiones 2027", "2027-01-11", "2027-01-29", 0],
  ["enrollment", "Inscripciones 2027", "2027-02-01", "2027-02-12", 0],
  ["extracurricular", "Feria de ciencias", "2026-10-09", "2026-10-09", 0],
  ["institutional", "Acto de clausura", "2026-11-27", "2026-11-27", 0],
];
for (const [key, title, from, until, noClass] of once) {
  const id = `event-${uuid(title)}`;
  lines.push(`INSERT INTO calendar_events(id,calendar_id,organization_id,category_id,title,starts_on,ends_on,part,no_class,rule_id,year,status,created_by,created_at,updated_at) SELECT ${q(id)},${calendar},${q(ORG)},${category(key)},${q(title)},${q(from)},${q(until)},'full',${noClass},NULL,NULL,'active',${q(ADMIN)},${q(AT)},${q(AT)} WHERE ${guard} AND ${calendar} IS NOT NULL AND NOT EXISTS(SELECT 1 FROM calendar_events WHERE calendar_id=${calendar} AND title=${q(title)} AND starts_on=${q(from)});`);
}
export const calendarEventsSql = lines.join("\n") + "\n";
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync("database/migrations/0063_demo_calendar_events.sql", calendarEventsSql);
  console.log(`0063_demo_calendar_events.sql: ${lines.filter(line => line.startsWith("INSERT")).length} statements`);
}
