import { mkdirSync } from "node:fs";
import { test, expect } from "./local-test";
import { e2eName, signIn, toast } from "./helpers";
import { pdfDocument } from "./office-fixture";

test("a book gets a record, an index, a plan map and a reading the student can mark; indexed resources are the proposal sources", async ({ page, browser }, info) => {
  test.setTimeout(120000);
  const title = e2eName(info, "Libro de polígonos");
  await signIn(page, "lucia.herrera", "/cursos/seed-course-mate6/biblioteca");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Recursos");
  await page.getByRole("button", { name: "Agregar recurso", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Agregar recurso" });
  await dialog.getByRole("radio", { name: "Archivo" }).check();
  await dialog.getByRole("button", { name: "Continuar" }).click();
  await dialog.getByLabel("Tipo", { exact: true }).selectOption({ label: "Libro" });
  await dialog.getByLabel("Título").fill(title);
  await dialog.getByLabel("Apellido").fill("López");
  await dialog.getByLabel("Nombre").fill("Ana");
  await dialog.getByLabel("Año").fill("2024");
  await dialog.getByLabel("Rol").selectOption("required");
  const share = dialog.getByRole("checkbox", { name: "Se puede compartir con estudiantes" });
  const press = (locator: ReturnType<typeof dialog.getByRole>) => info.project.name === "mobile" ? locator.evaluate((node: HTMLElement) => node.click()) : locator.click();
  if (info.project.name === "mobile") await share.evaluate((node: HTMLInputElement) => node.click());
  else await share.check();
  await dialog.getByLabel("Archivo").setInputFiles({ name: `${title}.pdf`, mimeType: "application/pdf", buffer: pdfDocument(["Primera pagina de demostracion", "Segunda pagina de demostracion"], ["Tema 1", "Ejercicios"]) });
  await press(dialog.getByRole("button", { name: "Subir documento" }));
  await expect(toast(page)).toContainText(`«${title}.pdf» se agregó`);
  await page.getByLabel("Buscar recursos").fill(title);
  await expect(page.getByRole("link", { name: title })).toBeVisible();
  await expect(page.getByText(/López/)).toBeVisible();
  await page.getByRole("button", { name: "Bibliografía APA" }).click();
  const apa = page.getByRole("dialog", { name: "Bibliografía APA" });
  await expect(apa.getByText(new RegExp(title.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")))).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(apa).toBeHidden();

  await page.getByRole("link", { name: title }).click();
  await page.getByRole("tab", { name: "Índice" }).click();
  await expect(page.getByRole("heading", { name: "Sin índice" })).toBeVisible();
  await page.getByRole("button", { name: "Capítulo" }).click();
  await page.getByLabel("Título de capítulo").fill("Capítulo 1");
  await page.getByLabel("Desde").fill("1");
  await page.getByLabel("Hasta").fill("1");
  await press(page.getByRole("button", { name: "Guardar índice" }));
  await expect(toast(page)).toContainText("Índice guardado");
  await page.getByRole("tab", { name: "Mapa al plan" }).click();
  const pages = page.getByLabel(/Páginas de/).first();
  await pages.fill("1");
  await press(page.getByRole("button", { name: "Confirmar" }).first());
  await expect(toast(page)).toContainText("confirmadas");

  await page.goto("/cursos/seed-course-mate6/contenido");
  await page.getByRole("button", { name: "Agregar lectura" }).first().click();
  const reading = page.getByRole("dialog", { name: "Agregar lectura" });
  await reading.getByLabel("Recurso").selectOption({ label: title });
  await reading.getByLabel("Capítulo o páginas").fill("Cap. 1");
  await press(reading.getByRole("button", { name: "Agregar lectura" }));
  await expect(toast(page)).toContainText("Lectura agregada");
  await expect(page.getByText(title).first()).toBeVisible();

  const student = await browser.newContext();
  const learner = await student.newPage();
  await learner.goto("/inicio");
  await learner.getByLabel("Código de sección o de lección").fill("DG-MATE-6A");
  await learner.getByRole("button", { name: "Abrir" }).click();
  await expect(learner.getByRole("heading", { level: 1 })).toHaveText("6.º A");
  expect(await learner.evaluate(async learnerId => (await fetch("/api/student/identity", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ learnerId }) })).ok, "seed-group-mat-6a-l01")).toBeTruthy();
  await learner.reload();
  const row = learner.getByRole("listitem").filter({ hasText: title });
  await row.getByRole("button", { name: "Marcar como leída" }).click();
  await expect(row.getByText("Leída")).toBeVisible();
  await student.close();

  await page.goto("/cursos/seed-course-mate6/asistente?paso=propuestas");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Planificar con IA");
  const sources = page.getByRole("group", { name: "Fuentes" });
  await expect(sources.getByRole("checkbox", { name: /Guía docente: polígonos/ })).toBeChecked();
  await expect(sources.getByRole("checkbox", { name: new RegExp(title.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")) })).toBeChecked();

  if (info.project.name !== "desktop") return;
  const dir = ".release-evidence/screenshots/lote-5";
  mkdirSync(dir, { recursive: true });
  const dismiss = () => page.evaluate(() => document.querySelectorAll("button[aria-label='Cerrar notificación']").forEach(node => (node as HTMLButtonElement).click()));
  const shoot = async (name: string) => {
    await dismiss();
    for (const width of [1440, 390]) {
      await page.setViewportSize({ width, height: width === 1440 ? 900 : 844 });
      await page.waitForTimeout(700);
      await page.screenshot({ path: `${dir}/${name}-${width}.png` });
    }
  };
  await page.goto("/cursos/seed-course-mate6/biblioteca");
  await expect(page.getByText(/indexados/)).toBeVisible();
  await shoot("recursos");
  await page.getByRole("button", { name: "Agregar recurso", exact: true }).click();
  await page.getByRole("dialog", { name: "Agregar recurso" }).getByRole("button", { name: "Continuar" }).click();
  await page.getByLabel("Tipo", { exact: true }).selectOption({ label: "Libro" });
  await page.waitForTimeout(400);
  await shoot("agregar-libro");
  await page.getByLabel("Tipo", { exact: true }).selectOption({ label: "Partitura" });
  await page.waitForTimeout(400);
  await shoot("agregar-partitura");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Bibliografía APA" }).click();
  await page.waitForTimeout(400);
  await shoot("bibliografia-apa");
  await page.keyboard.press("Escape");
  await page.getByRole("main").getByRole("link", { name: /Libro del estudiante/ }).click();
  await expect(page.getByRole("tab", { name: "Ficha" })).toBeVisible();
  await shoot("recurso-ficha");
  await page.getByRole("tab", { name: "Índice" }).click();
  await expect(page.getByLabel("Título de Tema 1. Polígonos")).toBeVisible();
  await shoot("recurso-indice");
  await page.goto("/cursos/seed-course-mate6/biblioteca");
  await page.getByLabel("Buscar recursos").fill(title);
  await page.getByRole("main").getByRole("link", { name: title }).click();
  await page.getByRole("tab", { name: "Índice" }).click();
  await page.getByRole("button", { name: "Extraer del PDF" }).click();
  await expect(toast(page)).toContainText("Índice extraído del PDF");
  await dismiss();
  await expect(page.getByLabel("Título de Tema 1")).toBeVisible();
  await shoot("recurso-indice-extraido");
  await page.getByRole("tab", { name: "Mapa al plan" }).click();
  await shoot("recurso-mapa");
  await page.goto("/cursos/seed-course-mate6/plan");
  await expect(page.getByText(/tienen al menos un recurso indexado/)).toBeVisible();
  await shoot("plan-cobertura");
  await page.goto("/cursos/seed-course-mate6/contenido");
  await expect(page.getByRole("heading", { name: "Lecturas" })).toBeVisible();
  await shoot("lecturas-unidad");
  await page.goto("/cursos/seed-course-mate6/asistente?paso=propuestas");
  await expect(page.getByRole("group", { name: "Fuentes" })).toBeVisible();
  await shoot("fuentes");
  const reader = await browser.newContext();
  const view = await reader.newPage();
  await view.goto("/inicio");
  await view.getByLabel("Código de sección o de lección").fill("DG-MATE-6A");
  await view.getByRole("button", { name: "Abrir" }).click();
  await expect(view.getByRole("heading", { name: "Lecturas" })).toBeVisible();
  for (const width of [1440, 390]) {
    await view.setViewportSize({ width, height: width === 1440 ? 900 : 844 });
    await view.waitForTimeout(400);
    await view.screenshot({ path: `${dir}/lecturas-estudiante-${width}.png` });
  }
  await reader.close();
  await page.setViewportSize({ width: 1365, height: 900 });
});
