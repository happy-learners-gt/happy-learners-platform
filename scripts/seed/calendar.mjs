// Builds 0058_demo_calendar.sql: the academic calendar (1.2.4) in the demo organization, on top of the pilot seed
// (0054). «Colegio Horizonte» gets its morning jornada (7:30, eight periods of 40 minutes, recess and snack) so a
// section's schedule can be set from its periods. Only runs in org-demo and steps aside when a jornada with that name
// already exists. Run: node scripts/seed/calendar.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { bellBlocks, bellTemplates } from "../../packages/domain/src/bell-schedules.ts";
import { pilotIds } from "./pilot.mjs";

const { ORG, ADMIN, uuid } = pilotIds;
const q = value => `'${String(value).replaceAll("'", "''")}'`;
const { draft } = bellTemplates.find(item => item.id === "matutina");
const id = `bell-${uuid("jornada-matutina")}`;
const row = [id, ORG, draft.name, draft.weekdays.join(","), JSON.stringify(draft.config), JSON.stringify(bellBlocks(draft.config)), ADMIN, "2026-10-28T14:00:00.000Z", "2026-10-28T14:00:00.000Z"];
export const calendarSql = [
  "-- Generated by scripts/seed/calendar.mjs. Do not edit by hand.",
  "-- The academic calendar (1.2.4) in the demo organization: «Jornada matutina» (7:30, eight periods of 40 minutes,",
  "-- recess and snack). Only runs in org-demo and only when no jornada has that name yet.",
  `INSERT INTO bell_schedules(id,organization_id,name,weekdays,config,blocks,created_by,created_at,updated_at) SELECT ${row.map(q).join(",")} WHERE EXISTS(SELECT 1 FROM organizations WHERE id='${ORG}') AND NOT EXISTS(SELECT 1 FROM bell_schedules WHERE organization_id='${ORG}' AND lower(name)=lower(${q(draft.name)}));`,
].join("\n") + "\n";
export const calendarId = id;
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync("database/migrations/0058_demo_calendar.sql", calendarSql);
  console.log("0058_demo_calendar.sql: 1 statement");
}
