// Generates apps/web/src/fluent/tokens.css from the official Fluent 2 tokens (@fluentui/tokens).
// The brand ramp is Happy Learners violet; everything else is the stock Fluent web light theme, and (ST-160) the stock
// Fluent web dark theme under :root[data-theme="dark"], with the same token names so every semantic token follows.
// Run `node scripts/fluent-tokens.mjs` after upgrading @fluentui/tokens; tests fail if the file drifts.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createDarkTheme, createLightTheme } from "@fluentui/tokens";

/** 16-step brand ramp (10 darkest → 160 lightest); step 80 is the brand colour #5b45e0. */
export const brand = {
  10: "#0d0828", 20: "#1a1145", 30: "#261a61", 40: "#31227a", 50: "#3c2a94", 60: "#4733ad", 70: "#513cc6", 80: "#5b45e0",
  90: "#6c58e5", 100: "#7d6be9", 110: "#8e7fed", 120: "#9f93f0", 130: "#b1a7f4", 140: "#c3bcf7", 150: "#d6d1fa", 160: "#e9e6fd",
};
export function css() {
  const light = createLightTheme(brand), dark = createDarkTheme(brand);
  const lines = Object.entries(light).map(([name, value]) => `  --${name}: ${value};`);
  const ramp = Object.entries(brand).map(([step, value]) => `  --brand-${step}: ${value};`);
  // Only what differs is repeated for dark: sizes, fonts, radii, durations and curves are shared.
  const darkLines = Object.entries(dark).filter(([name, value]) => light[name] !== value).map(([name, value]) => `  --${name}: ${value};`);
  return `/* Generated by scripts/fluent-tokens.mjs from @fluentui/tokens (Fluent 2 web light and dark themes, brand violet). Do not edit. */\n:root {\n${[...ramp, ...lines].join("\n")}\n}\n:root[data-theme="dark"] {\n${darkLines.join("\n")}\n}\n`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(new URL("../apps/web/src/fluent/tokens.css", import.meta.url), css());
