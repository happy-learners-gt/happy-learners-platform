import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";

test("SPR-002: educator creates, edits, orders, publishes, shares and observes completion", async ({ page, context }, info) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  const folder = `.release-evidence/screenshots/${info.project.name}`; await mkdir(folder, { recursive: true });
  const suffix = `${info.project.name}-${Date.now()}`;
  await page.goto("/");
  await page.getByLabel("Usuario", { exact: true }).fill("educador-demo");
  await page.getByLabel("Contraseña", { exact: true }).fill("Aprender-2026!");
  await page.getByRole("button", { name: /Entrar a mi espacio/ }).click();
  await page.getByRole("button", { name: "Preparar contenido" }).click();
  await expect(page.getByRole("button", { name: "Educadores", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Nuevo recurso" }).click();
  await page.getByLabel("Título del recurso").fill(`Hello ${suffix}`);
  await page.getByLabel("Descripción breve").fill("Saludo con un personaje ficticio.");
  await page.getByLabel("Contenido o dirección web").fill("Hello! My name is Sunny.");
  await page.getByRole("button", { name: "Guardar recurso", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Recurso guardado");
  await page.getByLabel("Buscar recursos").fill(suffix);
  await page.getByLabel("Filtrar por habilidad").selectOption("lectura");
  await expect(page.getByRole("heading", { name: `Hello ${suffix}` })).toBeVisible();
  await page.getByRole("button", { name: `Editar Hello ${suffix}`, exact: true }).click();
  await page.getByLabel("Descripción breve").fill("Saludo editado y persistente.");
  await page.getByRole("button", { name: "Guardar recurso", exact: true }).click();
  await expect(page.getByText("Saludo editado y persistente.")).toBeVisible();
  await page.screenshot({ path: `${folder}/s2-resources.png`, fullPage: true });
  await page.getByRole("button", { name: "Niveles y unidades", exact: true }).click();
  await page.getByRole("button", { name: "Nuevo nivel", exact: true }).click();
  await page.getByLabel("Nombre del nivel").fill(`Beginner ${suffix}`);
  await page.getByLabel("Descripción del nivel").fill("Primeros saludos en inglés.");
  await page.getByRole("button", { name: "Guardar nivel", exact: true }).click();
  await page.getByRole("button", { name: `Nueva unidad en Beginner ${suffix}`, exact: true }).click();
  await page.getByLabel("Nombre de la unidad").fill(`Greetings ${suffix}`);
  await page.getByLabel("Objetivo de la unidad").fill("Saludar y presentarse.");
  await page.getByRole("button", { name: "Guardar unidad", exact: true }).click();
  await expect(page.getByRole("heading", { name: `1. Greetings ${suffix}`, exact: true })).toBeVisible();
  await page.screenshot({ path: `${folder}/s2-curriculum.png`, fullPage: true });
  await page.getByRole("button", { name: "Lecciones", exact: true }).click();
  await page.getByRole("button", { name: "Nueva lección", exact: true }).click();
  await page.getByLabel("Título de la lección").fill(`Greetings ${suffix}`);
  await page.getByLabel("Objetivo de la lección").fill("Usar Hello! para saludar.");
  await page.getByLabel("Unidad de la lección").selectOption({ label: `Greetings ${suffix}` });
  await page.getByRole("button", { name: "Agregar actividad", exact: true }).click();
  let activity = page.locator("fieldset.activity-editor").nth(1);
  await activity.getByLabel("Tipo de actividad").selectOption("resource");
  await activity.getByLabel("Título de actividad").fill("Lee el saludo");
  await activity.getByLabel("Instrucciones de actividad").fill("Lee el recurso con un compañero.");
  await activity.getByLabel("Recurso vinculado").selectOption({ label: `Hello ${suffix}` });
  await page.getByRole("button", { name: "Agregar actividad", exact: true }).click();
  activity = page.locator("fieldset.activity-editor").nth(2);
  await activity.getByLabel("Tipo de actividad").selectOption("question");
  await activity.getByLabel("Título de actividad").fill("Elige el saludo");
  await activity.getByLabel("Instrucciones de actividad").fill("¿Cómo saludas?");
  await page.getByRole("button", { name: "Subir actividad 3", exact: true }).click();
  await expect(page.locator("fieldset.activity-editor").nth(1).getByLabel("Título de actividad")).toHaveValue("Elige el saludo");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  await page.getByRole("button", { name: "Publicar", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Lección publicada");
  const href = await page.getByRole("link", { name: "Abrir enlace público", exact: true }).getAttribute("href");
  expect(href).toContain("?code=");
  await page.getByLabel("Objetivo de la lección").fill("Usar Hello! y presentarse.");
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Borrador guardado");
  const student = await context.newPage(); await student.goto(href!);
  await expect(student.getByText("Usar Hello! para saludar.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Republicar", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Lección publicada");
  await student.reload();
  await expect(student.getByText("Usar Hello! y presentarse.", { exact: true })).toBeVisible();
  await expect(student.getByRole("heading", { name: "2. Elige el saludo", exact: true })).toBeVisible();
  await student.getByLabel("Hello!", { exact: true }).check();
  await expect(student.getByRole("status")).toContainText("¡Correcto!");
  await expect(student.getByText("Hello! My name is Sunny.", { exact: true })).toBeVisible();
  expect(await student.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await student.getByRole("button", { name: "Terminé la lección", exact: true }).click();
  await expect(student.getByText("¡Gracias por participar!")).toBeVisible();
  await student.screenshot({ path: `${folder}/s2-student.png`, fullPage: true });
  await student.close();
  await page.reload();
  await page.getByRole("button", { name: "Preparar contenido" }).click();
  await page.getByRole("button", { name: "Lecciones", exact: true }).click();
  const card = page.locator("article.editor-card").filter({ has: page.getByRole("heading", { name: `Greetings ${suffix}`, exact: true }) });
  await expect(card).toContainText("1 finalizaciones");
  await card.getByRole("button", { name: `Editar lección Greetings ${suffix}`, exact: true }).click();
  await expect(page.getByLabel("Objetivo de la lección")).toHaveValue("Usar Hello! y presentarse.");
  await page.screenshot({ path: `${folder}/s2-editor.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Cerrar sesión", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Iniciar sesión" })).toBeVisible();
  expect(errors).toEqual([]);
});
