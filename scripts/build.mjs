import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

process.chdir(fileURLToPath(new URL("../", import.meta.url)));
const sha = execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (!/^[a-f0-9]{40}$/.test(sha)) throw new Error("Expected a full Git SHA");
if (process.env.GITHUB_SHA && process.env.GITHUB_SHA !== sha) throw new Error("Checkout does not match GITHUB_SHA");
mkdirSync("apps/api/src/generated", { recursive: true });
writeFileSync("apps/api/src/generated/version.ts", `// Generated by scripts/build.mjs\nexport const sha = ${JSON.stringify(sha)};\n`);
rmSync("build", { recursive: true, force: true });
execFileSync("npm", ["run", "build:web"], { stdio: "inherit" });
execFileSync("node_modules/.bin/wrangler", ["deploy", "--dry-run", "--config", "infrastructure/wrangler.jsonc", "--outdir", fileURLToPath(new URL("../build/worker", import.meta.url))], { stdio: "inherit" });
cpSync("apps/web/dist", "build/web", { recursive: true });
const config = JSON.parse(readFileSync("infrastructure/wrangler.jsonc", "utf8"));
delete config.$schema;
config.main = "worker/index.js";
config.assets.directory = "web";
config.no_bundle = true;
writeFileSync("build/wrangler.json", JSON.stringify(config, null, 2) + "\n");
writeFileSync("build/version.json", JSON.stringify({ sha }) + "\n");
